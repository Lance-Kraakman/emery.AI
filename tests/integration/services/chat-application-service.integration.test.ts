import { describe, test, expect, beforeAll, afterAll, beforeEach, afterEach } from 'vitest';
import { 
  getChatApplicationService, 
  getContextAwareDb, 
  initializeDI 
} from '@/ddd/application/di/container';
import { testClient } from '../shared/integration-helpers';
import { OrganizationId, UserId } from '@/ddd/domain/shared/value-objects';
import type { TestCase } from '../../shared/types';
import type { CreateChatCommand } from '@/ddd/application/services/chat/chat-application-service';

// AIDEV-NOTE: Chat Application Service integration tests focusing on core DDD functionality
// Tests Value Object usage, repository integration, and business logic validation

interface CreateChatInput {
  title: string;
  organizationId: number;
  createdBy: string;
  description?: string;
  domainType?: 'table' | 'agent';
  domainId?: number;
}

interface CreateChatOutput {
  success: boolean;
  error?: string;
  hasProperIds?: boolean;
  hasDomainContext?: boolean;
  hasAutoGeneratedTitle?: boolean;
}

describe('Chat Application Service Integration Tests', () => {
  let testOrgId: number;
  let testUserId: string;

  beforeAll(() => {
    // Initialize DI container with test database clients
    initializeDI(testClient.db as any, testClient.db as any);
  });

  afterAll(async () => {
    await testClient.disconnect();
  });

  beforeEach(async () => {
    // Create test organization and context
    const { createTestOrganization } = await import('../shared/test-setup');
    const context = await createTestOrganization('Chat Test Organization');
    
    testOrgId = context.organizationId;
    testUserId = context.ownerUserId;
    
    // Set RLS context for testing
    const contextDb = getContextAwareDb();
    contextDb.setContext(testUserId, testOrgId);
  });

  afterEach(async () => {
    // Clean test data and clear context
    const contextDb = getContextAwareDb();
    contextDb.clearContext();
    await testClient.cleanTestData();
  });

  describe('Create Chat Operations', () => {
    const createChatTestCases: TestCase<CreateChatInput, CreateChatOutput>[] = [
      {
        name: 'should create basic chat with proper Value Objects',
        input: {
          title: 'Test Chat',
          organizationId: 0, // Will be set dynamically
          createdBy: '', // Will be set dynamically
          description: 'A test chat'
        },
        expected: { 
          success: true, 
          hasProperIds: true 
        }
      },
      {
        name: 'should create organization-wide chat without domain connection',
        input: {
          title: 'Organization Chat',
          organizationId: 0, // Will be set dynamically
          createdBy: '', // Will be set dynamically
          description: 'Organization-wide chat without domain connection'
        },
        expected: { 
          success: true, 
          hasProperIds: true 
        }
      },
      {
        name: 'should auto-generate title when empty title provided',
        input: {
          title: '',
          organizationId: 0, // Will be set dynamically
          createdBy: '' // Will be set dynamically
        },
        expected: { 
          success: true,
          hasProperIds: true,
          hasAutoGeneratedTitle: true
        }
      },
      {
        name: 'should reject chat with title too long',
        input: {
          title: 'x'.repeat(250), // Exceeds 200 character limit
          organizationId: 0, // Will be set dynamically
          createdBy: '' // Will be set dynamically
        },
        expected: { 
          success: false, 
          error: 'Chat title must be less than 200 characters' 
        }
      }
    ];

    createChatTestCases.forEach((testCase) => {
      test(testCase.name, async () => {
        const chatApplicationService = getChatApplicationService();
        
        // Update test case input with dynamic values
        testCase.input.organizationId = testOrgId;
        testCase.input.createdBy = testUserId;
        
        const command: CreateChatCommand = {
          title: testCase.input.title,
          organizationId: testCase.input.organizationId,
          createdBy: testCase.input.createdBy,
          description: testCase.input.description,
          domainType: testCase.input.domainType,
          domainId: testCase.input.domainId
        };

        console.log(`🔍 Creating chat with command:`, {
          title: command.title,
          organizationId: command.organizationId,
          createdBy: command.createdBy,
          domainType: command.domainType
        });

        const result = await chatApplicationService.createChat(command);
        
        console.log(`🔍 Chat creation result:`, {
          success: result.success,
          error: result.error,
          hasData: !!result.data
        });
        
        expect(result.success).toBe(testCase.expected.success);
        
        if (testCase.expected.error) {
          expect(result.error).toContain(testCase.expected.error);
        }
        
        if (testCase.expected.success) {
          expect(result.data).toBeDefined();
          
          if (testCase.expected.hasAutoGeneratedTitle) {
            // Title should be auto-generated, not empty
            expect(result.data?.title).toBeTruthy();
            expect(result.data?.title).not.toBe('');
            expect(result.data?.title.length).toBeGreaterThan(0);
          } else {
            expect(result.data?.title).toBe(testCase.input.title);
          }
          
          if (testCase.expected.hasProperIds) {
            // Verify proper Value Object usage
            expect(result.data?.id).toBeDefined();
            expect(result.data?.organizationId).toBeDefined();
            expect(result.data?.createdBy).toBeDefined();
            
            // Verify Value Objects have proper structure
            expect(typeof result.data?.id.value).toBe('string');
            expect(typeof result.data?.organizationId.value).toBe('number');
            expect(typeof result.data?.createdBy.value).toBe('string');
          }
          
          if (testCase.expected.hasDomainContext) {
            expect(result.data?.contextMetadata).toBeDefined();
            expect(result.data?.contextMetadata?.contextType).toBe(testCase.input.domainType);
            expect(result.data?.contextMetadata?.domainSchema?.id).toBe(testCase.input.domainId);
          }
        }
      });
    });
  });

  describe('Chat Business Logic', () => {
    let createdChatId: string;

    beforeEach(async () => {
      // Create a test chat for business logic tests
      const chatApplicationService = getChatApplicationService();
      const createResult = await chatApplicationService.createChat({
        title: 'Business Logic Test Chat',
        organizationId: testOrgId,
        createdBy: testUserId,
        description: 'Chat for testing business logic'
      });
      
      expect(createResult.success).toBe(true);
      expect(createResult.data).toBeDefined();
      createdChatId = createResult.data!.id.value;
    });

    test('should allow creator to access chat', async () => {
      const chatApplicationService = getChatApplicationService();
      
      const result = await chatApplicationService.getChatHistory({
        chatId: createdChatId,
        organizationId: testOrgId,
        userId: testUserId
      });
      
      expect(result.success).toBe(true);
    });

    test('should prevent access from different organization', async () => {
      // Create a second organization
      const { createTestOrganization } = await import('../shared/test-setup');
      const org2Context = await createTestOrganization('Chat Test Organization 2');
      
      const chatApplicationService = getChatApplicationService();
      
      const result = await chatApplicationService.getChatHistory({
        chatId: createdChatId,
        organizationId: org2Context.organizationId, // Different org
        userId: org2Context.ownerUserId
      });
      
      expect(result.success).toBe(false);
      expect(result.error).toContain('Chat not found or access denied');
    });
  });

  describe('Chat Repository Integration', () => {
    test('should properly convert Value Objects in repository operations', async () => {
      const chatApplicationService = getChatApplicationService();
      
      // Create chat
      const createResult = await chatApplicationService.createChat({
        title: 'Repository Integration Test',
        organizationId: testOrgId,
        createdBy: testUserId
      });
      
      expect(createResult.success).toBe(true);
      expect(createResult.data).toBeDefined();
      
      // Verify the chat was created with proper Value Objects
      const createdChat = createResult.data!;
      
      // Test Value Object methods
      expect(createdChat.organizationId.equals(OrganizationId.fromNumber(testOrgId))).toBe(true);
      expect(createdChat.createdBy.equals(UserId.fromString(testUserId))).toBe(true);
      
      // Test business methods work with Value Objects
      expect(createdChat.canUserAccess(
        UserId.fromString(testUserId), 
        OrganizationId.fromNumber(testOrgId)
      )).toBe(true);
      
      expect(createdChat.canUserEdit(UserId.fromString(testUserId))).toBe(true);
      
      expect(createdChat.canUserMessage(
        UserId.fromString(testUserId), 
        OrganizationId.fromNumber(testOrgId)
      )).toBe(true);
    });
  });
});