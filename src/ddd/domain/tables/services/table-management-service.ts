/**
 * Table Management Domain Service
 * 
 * Domain service that orchestrates table operations.
 * Contains business logic that doesn't naturally fit in entities
 * or value objects, but coordinates between multiple domain services.
 * 
 * This service is pure domain logic - no infrastructure dependencies.
 */

import { DynamicTable } from '../entities/dynamic-table';
import { TableId, OrganizationId, DatabaseId, UserId } from '../../shared/value-objects';
import { Result, ResultHelpers } from '../../shared/result';
import type { ITableDataStorageService } from './table-data-storage-service.interface';
import type { ITableQueryService } from './table-query-service.interface';
import type { IDynamicTableRepository } from '../repositories/dynamic-table-repository';

export interface CreateTableRequest {
  name: string;
  databaseId: DatabaseId;
  organizationId: OrganizationId;
  createdBy: string;
  description?: string;
}

export interface UpdateTableRequest {
  tableId: TableId;
  name?: string;
  description?: string;
}

/**
 * Domain service for table management operations
 */
export class TableManagementService {
  constructor(
    private readonly tableRepository: IDynamicTableRepository,
    private readonly dataStorageService: ITableDataStorageService,
    private readonly queryService: ITableQueryService
  ) {}

  /**
   * Create a new table with proper domain validation
   */
  async createTable(request: CreateTableRequest): Promise<Result<DynamicTable>> {
    try {
      // Domain validation: check if table name is available
      const nameCheckResult = await this.queryService.isTableNameAvailable(
        request.name,
        request.organizationId
      );

      if (!nameCheckResult.success) {
        return ResultHelpers.failure(`Failed to check table name availability: ${nameCheckResult.error}`);
      }

      if (!nameCheckResult.data) {
        return ResultHelpers.failure(`Table name '${request.name}' is already taken`);
      }

      // Create table through repository (handles both database and storage creation)
      const tableResult = await this.tableRepository.create({
        databaseId: request.databaseId,
        organizationId: request.organizationId,
        name: request.name,
        description: request.description,
        storageLocation: '', // Will be generated by repository
        createdBy: UserId.fromString(request.createdBy)
      });

      return ResultHelpers.success(tableResult);

    } catch (error) {
      return ResultHelpers.failure(error instanceof Error ? error.message : 'Failed to create table');
    }
  }

  /**
   * Update table metadata with domain validation
   */
  async updateTable(request: UpdateTableRequest): Promise<Result<DynamicTable>> {
    try {
      // Get existing table
      const existingTableResult = await this.queryService.findTableById(request.tableId);

      if (!existingTableResult.success) {
        return ResultHelpers.failure(`Failed to find table: ${existingTableResult.error}`);
      }

      if (!existingTableResult.data) {
        return ResultHelpers.failure('Table not found');
      }

      const existingTable = existingTableResult.data;

      // If name is being changed, check availability
      if (request.name && request.name !== existingTable.name) {
        const nameCheckResult = await this.queryService.isTableNameAvailable(
          request.name,
          existingTable.organizationId,
          existingTable.id
        );

        if (!nameCheckResult.success) {
          return ResultHelpers.failure(`Failed to check table name availability: ${nameCheckResult.error}`);
        }

        if (!nameCheckResult.data) {
          return ResultHelpers.failure(`Table name '${request.name}' is already taken`);
        }
      }

      // Update table entity using domain methods
      if (request.name) {
        existingTable.updateName(request.name);
      }

      if (request.description !== undefined) {
        existingTable.updateDescription(request.description);
      }

      return ResultHelpers.success(existingTable);

    } catch (error) {
      return ResultHelpers.failure(error instanceof Error ? error.message : 'Failed to update table');
    }
  }

  /**
   * Delete a table with proper cleanup
   */
  async deleteTable(tableId: TableId): Promise<Result<void>> {
    try {
      // Get table to delete
      const tableResult = await this.queryService.findTableById(tableId);

      if (!tableResult.success) {
        return ResultHelpers.failure(`Failed to find table: ${tableResult.error}`);
      }

      if (!tableResult.data) {
        return ResultHelpers.failure('Table not found');
      }

      const table = tableResult.data;

      // Delete table storage
      const deleteResult = await this.dataStorageService.deleteTable(table);

      if (!deleteResult.success) {
        return ResultHelpers.failure(`Failed to delete table storage: ${deleteResult.error}`);
      }

      return ResultHelpers.success(undefined);

    } catch (error) {
      return ResultHelpers.failure(error instanceof Error ? error.message : 'Failed to delete table');
    }
  }

  /**
   * Add rows to a table with domain validation
   */
  async addRowsToTable(tableId: TableId, rows: any[]): Promise<Result<void>> {
    try {
      // Get table
      const tableResult = await this.queryService.findTableById(tableId);

      if (!tableResult.success) {
        return ResultHelpers.failure(`Failed to find table: ${tableResult.error}`);
      }

      if (!tableResult.data) {
        return ResultHelpers.failure('Table not found');
      }

      const table = tableResult.data;

      // Convert row data to Row entities (this would need more sophisticated logic)
      // For now, assuming rows are already Row entities
      const rowEntities = rows; // This would need proper conversion

      // Store rows
      const storeResult = await this.dataStorageService.storeRows(rowEntities, table);

      if (!storeResult.success) {
        return ResultHelpers.failure(`Failed to store rows: ${storeResult.error}`);
      }

      return ResultHelpers.success(undefined);

    } catch (error) {
      return ResultHelpers.failure(error instanceof Error ? error.message : 'Failed to add rows to table');
    }
  }
}
